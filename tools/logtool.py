def reproduce_rows():
    f = ROOT / "REPRODUCE.md"
    if not f.exists():
        sys.exit("REPRODUCE.md not found")
    rows = []
    for line in f.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or not line.lstrip().startswith("|"):
            continue
        m = re.search(r"`([^`]+)`", cells[1])
        if not m or "<" in m.group(1):
            continue
        rows.append((cells[0], m.group(1)))
    return rows


def cmd_reproduce(a):
    rows = reproduce_rows()
    if not rows:
        sys.exit("REPRODUCE.md has no table rows with a command in `backticks`.")
    if a.list:
        for item, c in rows:
            print(f"{item:30s} {c}")
        return
    if a.items:
        rows = [r for r in rows if any(x.lower() in r[0].lower() for x in a.items)]
        if not rows:
            sys.exit("no matching item; see --list")
    done = []
    for item, c in rows:
        args = shlex.split(c)
        if args and args[0] in ("python", "python3", "py"):
            args[0] = sys.executable
        if a.quick:
            args.append("--quick")
        print(f"\n=== {item}: {c}{' --quick' if a.quick else ''}")
        t0 = time.time()
        rc = subprocess.run(args, cwd=ROOT).returncode
        done.append((item, rc, time.time() - t0))
        if rc != 0 and not a.keep_going:
            break
    print("\n| Item | Result | Seconds |\n|---|---|---:|")
    for item, rc, sec in done:
        print(f"| {item} | {'ok' if rc == 0 else 'FAILED'} | {sec:.0f} |")
    if any(rc for _, rc, _ in done) or len(done) < len(rows):
        sys.exit(1)


