def first_commit(relpath: str, ref: str = "HEAD"):
    """(ISO date, author name) of the commit that added a file, or None."""
    out = git("log", ref, "--diff-filter=A", "--format=%aI|%an", "--", relpath, check=False)
    if not out:
        return None
    d, n = out.splitlines()[-1].split("|", 1)
    return d[:10], n


def n_edits(relpath: str, ref: str = "HEAD") -> int:
    out = git("log", ref, "--format=%H", "--", relpath, check=False)
    return max(0, len(out.splitlines()) - 1)


