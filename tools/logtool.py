def ask(question, default=""):
    """Prompt on the terminal; returns the default when not interactive."""
    if not sys.stdin.isatty():
        return default
    suffix = f" [{default}]" if default else ""
    try:
        ans = input(f"{question}{suffix}: ").strip()
    except EOFError:
        return default
    return ans or default


def yes(question, default=True, assume=False):
    if assume:
        return True
    ans = ask(question + (" (Y/n)" if default else " (y/N)"), "y" if default else "n")
    return ans.lower().startswith("y")


def tex_escape(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


class Entry:
    def __init__(self, path: Path):
        self.path = path
        self.name = path.name
        self.text = path.read_text(encoding="utf-8")
        m = ENTRY_RE.match(path.name)
        self.file_date = m.group(1) if m else None
        self.title = ""
        self.fields = {}
        self.items = {}           # sub-items of a field, e.g. the list under "Runs"
        self.sections = {}
        self._parse()

    def _parse(self):
        current = None
        in_code = False
        last_field = None
        for line in self.text.splitlines():
            if line.strip().startswith("```"):
                in_code = not in_code
            if not in_code and line.startswith("# ") and not self.title:
                self.title = line[2:].strip()
                continue
            if not in_code and line.startswith("## "):
                current = line[3:].strip()
                self.sections[current] = []
                continue
            if current is None:
                fm = FIELD_RE.match(line)
                sub = re.match(r"^\s{2,}[-*]\s+(.*\S)\s*$", line)
                if fm:
                    last_field = fm.group(1).strip()
                    self.fields[last_field] = fm.group(2).strip()
                    self.items[last_field] = []
                elif sub and last_field:
                    self.items[last_field].append(sub.group(1))
            else:
                self.sections[current].append(line)

    @property
    def date(self):
        return self.fields.get("Date") or self.file_date or ""

    @property
    def authors(self):
        a = self.fields.get("Author", "")
        return [x.strip() for x in re.split(r",|;| and ", a) if x.strip()]

    def section_text(self, name):
        body = "\n".join(self.sections.get(name, []))
        return re.sub(r"<!--.*?-->", "", body, flags=re.S).strip()


def added_times(ref: str = "HEAD") -> dict:
    """{entry file name: time (seconds) of the commit that added it}."""
    out, t = {}, None
    r = subprocess.run(["git", "log", ref, "--reverse", "--diff-filter=A", "--format=@%at",
                        "--name-only", "--", "log/"], cwd=ROOT, capture_output=True, text=True)
    for line in r.stdout.splitlines():
        if line.startswith("@"):
            t = int(line[1:])
        elif line.strip() and t is not None:
            out.setdefault(Path(line.strip()).name, t)
    return out


def entries(log_dir: Path = LOG, ref: str = "HEAD") -> list:
    """Entries in chronological order: by date, then by when they were first
    committed (entries not committed yet come last), then by name."""
    out = [Entry(p) for p in sorted(log_dir.glob("*.md"))
           if p.name.lower() != "readme.md" and not p.name.startswith("_")]
    added = added_times(ref) if (ROOT / ".git").exists() else {}
    return sorted(out, key=lambda e: (e.date, added.get(e.name, float("inf")), e.name))


