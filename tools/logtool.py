MAX_MB = 20


def push():
    has_upstream = subprocess.run(["git", "rev-parse", "--abbrev-ref", "@{u}"], cwd=ROOT,
                                  capture_output=True).returncode == 0
    if not git("remote", check=False):
        print("No remote repository configured: committed locally only.")
        return
    if has_upstream:
        r = subprocess.run(["git", "pull", "--no-rebase", "--no-edit", "-q"], cwd=ROOT,
                           capture_output=True, text=True)
        conflicts = git("diff", "--name-only", "--diff-filter=U", check=False).splitlines()
        if r.returncode != 0 and conflicts == ["log/README.md"]:
            # only the generated index conflicts: regenerate it and finish the merge
            cmd_index(quiet=True)
            git("add", "log/README.md")
            git("commit", "-q", "--no-edit")
            print("merged the others' changes (log index regenerated)")
        elif r.returncode != 0:
            sys.exit("Could not merge the others' changes automatically:\n" + r.stdout + r.stderr +
                     "\nOpen the files listed as CONFLICT, keep the right content, remove the "
                     "<<<<<<< ======= >>>>>>> lines, then run: python tools/logtool.py save")
        cmd = ["git", "push", "-q"]
    else:
        cmd = ["git", "push", "-q", "-u", "origin", "HEAD"]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("Push failed:\n" + r.stderr)
    print("pushed to GitHub")


def pending_entries():
    """Entry files that are new or changed since the last commit."""
    out = []
    for p in status_paths("log"):
        if p.startswith("log/") and p.count("/") == 1 and p.endswith(".md") \
                and not p.endswith("README.md") and (ROOT / p).exists():
            out.append(ROOT / p)
    return out


def rename_clashing_entries():
    """A new (never committed) entry whose file name another member has meanwhile
    pushed is renamed to the next free name, with its frozen figures."""
    remote = set()
    if git("remote", check=False):
        try:
            subprocess.run(["git", "fetch", "-q"], cwd=ROOT, capture_output=True, timeout=30)
        except (subprocess.TimeoutExpired, OSError):
            return
        up = git("rev-parse", "--abbrev-ref", "@{u}", check=False)
        if up:
            remote = {Path(x).name for x in
                      git("ls-tree", "--name-only", up, "log/", check=False).splitlines()}
    for p in pending_entries():
        if p.name not in remote or git("ls-files", p.relative_to(ROOT).as_posix(), check=False):
            continue
        taken = remote | {q.name for q in LOG.glob("*.md")}
        base, k = re.sub(r"-\d+$", "", p.stem), 2
        while f"{base}-{k}.md" in taken:
            k += 1
        new = p.with_name(f"{base}-{k}.md")
        text = p.read_text(encoding="utf-8").replace(f"figs/{p.stem}/", f"figs/{new.stem}/")
        new.write_text(text, encoding="utf-8")
        p.unlink()
        if frozen_dir(p).exists():
            frozen_dir(p).rename(frozen_dir(new))
        print(f"renamed {p.name} -> {new.name} (another member used that name first)")


def cmd_save(a):
    need_git_name()
    rename_clashing_entries()
    if (ROOT / ".git" / "MERGE_HEAD").exists():
        left = git("diff", "--name-only", "--diff-filter=U", check=False).splitlines()
        left = [f for f in left if f != "log/README.md"]
        if left:
            sys.exit("A merge is in progress with unresolved conflicts in: " + ", ".join(left) +
                     "\nEdit these files (remove the <<<<<<< ======= >>>>>>> markers), then save again.")
    project = load_project()
    held = []
    for p in pending_entries():
        errs, copied = freeze_figures(p)
        for c in copied:
            print(f"froze {c}")
        e = Entry(p)
        cerrs, warns = check_entry(e, project, pending=True, figures=False)
        for m in errs + cerrs:
            print(f"ERROR   {p.name}: {m}")
        for m in warns:
            print(f"warning {p.name}: {m}")
        if errs or cerrs:
            held.append(p)
    held_names = {p.name for p in held}
    cmd_index(quiet=True, exclude=held_names)          # index of what is committed
    git("add", "-A")
    for p in held:                                      # unfinished entries stay out
        git("reset", "-q", "--", p.relative_to(ROOT).as_posix(), check=False)
        fd = frozen_dir(p)
        if fd.exists():
            git("reset", "-q", "--", fd.relative_to(ROOT).as_posix(), check=False)
    for p in pending_entries():                         # frozen figures always go with their entry
        fd = frozen_dir(p)
        if p.name not in held_names and fd.exists():
            git("add", "-f", "--", fd.relative_to(ROOT).as_posix())
    staged = git("diff", "--cached", "--name-only").splitlines()
    big = [f for f in staged if (ROOT / f).is_file()
           and (ROOT / f).stat().st_size > MAX_MB * 2**20]
    if big:
        git("reset", "-q", "--", *big)
        print(f"not committed (larger than {MAX_MB} MB; add them to .gitignore): {', '.join(big)}")
        staged = [f for f in staged if f not in big]
    if held:
        print("held back (not committed until fixed): " + ", ".join(p.name for p in held))
    if staged:
        titles = [Entry(ROOT / f).title for f in staged
                  if f.startswith("log/") and f.count("/") == 1 and ENTRY_RE.match(Path(f).name)
                  and (ROOT / f).exists()]
        msg = a.message or ("Log: " + "; ".join(titles) if titles else "Update " +
                            ", ".join(sorted({f.split('/')[0] for f in staged})))
        git("commit", "-q", "-m", msg)
        print(f"committed {len(staged)} file(s): {msg}")
    else:
        print("nothing to commit")
    cmd_index(quiet=True)                               # local index again lists everything
    push()
    if held:
        sys.exit(1)


