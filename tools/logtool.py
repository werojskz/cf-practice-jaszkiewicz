def maths_problems(text):
    """Inline formulas $...$ that pandoc (PDF export) and GitHub do not recognise."""
    out = []
    body = re.sub(r"```.*?```|<!--.*?-->", lambda m: " " * len(m.group(0)), text, flags=re.S)
    body = re.sub(r"\$`[^`\n]*`\$", lambda m: " " * len(m.group(0)), body)    # GitHub's $`...`$
    body = re.sub(r"`[^`\n]*`", lambda m: " " * len(m.group(0)), body)
    body = re.sub(r"\$\$.*?\$\$", lambda m: re.sub(r"[^\n]", " ", m.group(0)), body, flags=re.S)
    for para in re.split(r"\n\s*\n", body):
        pos = [m.start() for m in re.finditer(r"(?<!\\)\$", para)]
        for a, b in zip(pos[0::2], pos[1::2]):
            f = para[a:b + 1]
            short = " ".join(f.split())[:40]
            if "\n" in f:
                out.append(f"formula {short} is broken over two lines: keep $...$ on one line")
            elif f[1:2].isspace():
                out.append(f"formula {short}: no space directly after the opening $")
            elif f[-2:-1].isspace():
                out.append(f"formula {short}: no space directly before the closing $")
            elif para[b + 1:b + 2].isdigit():
                out.append(f"formula {short}: a digit directly after the closing $ "
                           "(add a space, or put the digit inside the formula)")
        if len(pos) % 2:
            tail = " ".join(para[pos[-1]:pos[-1] + 30].split())
            out.append(f"unmatched $ near '{tail}' (write \\$ for a dollar sign)")
    return out


def check_entry(e: Entry, project: dict, pending=False, figures=True):
    """pending: entry not yet committed (save will freeze its figures);
    figures=False: skip figure links (save has already reported them)."""
    errors, warnings = [], []
    if not ENTRY_RE.match(e.name):
        errors.append("file name must be YYYY-MM-DD_short-title.md (lower case, hyphens)")
    if not e.title:
        errors.append("missing title line '# ...'")
    for f in REQUIRED_FIELDS:
        if not e.fields.get(f):
            errors.append(f"missing field '- **{f}:** ...'")
    d = e.fields.get("Date", "")
    if d:
        try:
            dt.date.fromisoformat(d)
        except ValueError:
            errors.append(f"Date '{d}' is not YYYY-MM-DD")
        if e.file_date and d != e.file_date:
            errors.append(f"Date field {d} differs from file name date {e.file_date}")
    code = e.fields.get("Code", "")
    no_code = code.lower() in NO_CODE
    if code and not no_code:
        m = re.search(r"`?([0-9a-f]{7,40})`?", code)
        if not m:
            warnings.append("Code field has no commit hash")
        elif (ROOT / ".git").exists() and subprocess.run(
                ["git", "cat-file", "-e", m.group(1) + "^{commit}"], cwd=ROOT,
                capture_output=True).returncode != 0:
            warnings.append(f"commit {m.group(1)} not found in this repository")
        if "uncommitted" in code:
            warnings.append("the code had uncommitted changes: say in 'Code and runs' what differed")
    names = member_names(project)
    for au in e.authors:
        if names and au not in names:
            warnings.append(f"author '{au}' is not a member listed in project.json")
    for s in REQUIRED_SECTIONS:
        if s not in e.sections:
            errors.append(f"missing section '## {s}'")
        elif not e.section_text(s):
            errors.append(f"section '## {s}' is empty")
    for s in e.sections:
        if s not in REQUIRED_SECTIONS + OPTIONAL_SECTIONS:
            warnings.append(f"unexpected section '## {s}' (use ### for subsections)")
    if "AI assistance" in e.sections and not e.section_text("AI assistance"):
        warnings.append("empty '## AI assistance' section: fill it in or delete it")
    res = "\n".join(e.sections.get("Results", []))
    if not no_code and not re.search(r"\|\s*-{3,}|!\[|```|\.pdf\)", res):
        warnings.append("Results contain no table, figure or program output")
    body = re.sub(r"```.*?```|<!--.*?-->", "", e.text, flags=re.S)
    body = re.sub(r"`[^`\n]*`", "", body)
    if body.count("$$") % 2:
        errors.append("unbalanced $$ (display maths)")
    for m in maths_problems(e.text):
        warnings.append(m + " -- it will show as raw text on GitHub and break the PDF export")
    frozen = frozen_dir(e.path).resolve()
    for target in (figure_links(e.text) if figures else []):
        if re.match(r"[a-z]+://", target) or outside_repo(target, e.path):
            errors.append(f"figure outside the repository: {target}")
            continue
        src = (e.path.parent / target).resolve()
        if not src.exists():
            errors.append(f"figure not found: {target}")
        elif src.parent != frozen:
            msg = f"figure {target} is not in the entry's folder log/figs/{e.path.stem}/"
            if pending:
                pass                                   # save freezes it before checking
            else:
                errors.append(msg + " (run: python tools/logtool.py save)")
    for target in LINK_RE.findall(body):
        if re.match(r"[a-z]+://|#|mailto:", target):
            continue
        if not (e.path.parent / target.split("#")[0]).exists():
            errors.append(f"linked file not found: {target}")
    return errors, warnings


