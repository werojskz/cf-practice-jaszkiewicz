IMG_LINK_RE = re.compile(r"(!\[[^\]]*\]\()([^)\s]+)(\))")
PROTECTED_RE = re.compile(r"(```.*?```|<!--.*?-->|`[^`\n]*`)", re.S)


def _outside_protected(text, fn):
    """Apply fn to the parts of text outside code blocks, inline code and comments."""
    parts = PROTECTED_RE.split(text)
    return "".join(p if i % 2 else fn(p) for i, p in enumerate(parts))


def figure_links(text):
    found = []
    _outside_protected(text, lambda s: found.extend(m.group(2) for m in IMG_LINK_RE.finditer(s)) or s)
    return found


def frozen_dir(entry_path: Path) -> Path:
    return entry_path.parent / "figs" / entry_path.stem


def outside_repo(target: str, entry_path: Path):
    if re.match(r"^[A-Za-z]:[\\/]|^[/\\~]", target):
        return True
    try:
        (entry_path.parent / target).resolve().relative_to(ROOT.resolve())
        return False
    except ValueError:
        return True


def _same(a: Path, b: Path) -> bool:
    return a.stat().st_size == b.stat().st_size and a.read_bytes() == b.read_bytes()


def freeze_figures(entry_path: Path):
    """Copy every embedded figure into log/figs/<entry>/ and point the links there.
    Returns (errors, copied files)."""
    errors, copied = [], []
    folder = frozen_dir(entry_path)

    def fix(m):
        target = m.group(2)
        if re.match(r"[a-z]+://", target):
            errors.append(f"figure from the web: {target} (save it into the repository first)")
            return m.group(0)
        if outside_repo(target, entry_path):
            errors.append(f"figure outside the repository: {target} "
                          "(copy it into the repository folder first)")
            return m.group(0)
        src = (entry_path.parent / target).resolve()
        if not src.is_file():
            errors.append(f"figure not found: {target}")
            return m.group(0)
        if src.parent == folder.resolve():
            return m.group(0)
        folder.mkdir(parents=True, exist_ok=True)
        dst, k = folder / src.name, 2
        while dst.exists() and not _same(dst, src):
            dst, k = folder / f"{src.stem}-{k}{src.suffix}", k + 1
        if not dst.exists():
            shutil.copy2(src, dst)
            copied.append(dst.relative_to(ROOT).as_posix())
        return m.group(1) + dst.relative_to(entry_path.parent).as_posix() + m.group(3)

    text = entry_path.read_text(encoding="utf-8")
    new = _outside_protected(text, lambda s: IMG_LINK_RE.sub(fix, s))
    if new != text and not errors:
        entry_path.write_text(new, encoding="utf-8")
    return errors, copied


def png_text(path: Path) -> dict:
    """Text chunks of a PNG file (where the experiment helper stores provenance)."""
    import zlib
    data = path.read_bytes()
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        return {}
    out, i = {}, 8
    while i + 8 <= len(data):
        n = int.from_bytes(data[i:i + 4], "big")
        typ, body = data[i + 4:i + 8], data[i + 8:i + 8 + n]
        if typ == b"tEXt":
            k, _, v = body.partition(b"\x00")
            out[k.decode("latin-1")] = v.decode("latin-1")
        elif typ == b"iTXt":
            k, _, rest = body.partition(b"\x00")
            comp, rest = rest[0], rest[2:]
            _, _, rest = rest.partition(b"\x00")
            _, _, txt = rest.partition(b"\x00")
            out[k.decode("utf-8")] = (zlib.decompress(txt) if comp else txt).decode("utf-8")
        elif typ == b"IEND":
            break
        i += 12 + n
    return out


def cmd_figinfo(a):
    """Provenance of the figures of an entry (or of given image files).
    An entry can be given by its file name or any part of it, e.g. 'antithetic'."""
    files = []
    for x in a.items:
        p = Path(x)
        cand = [p if p.is_absolute() else Path.cwd() / p, ROOT / p]
        image = next((c for c in cand if c.is_file() and c.suffix.lower() != ".md"), None)
        if image:
            files.append(image.resolve())
            continue
        stem = Path(x).name[:-3] if x.endswith(".md") else Path(x).name
        es = [e for e in entries()]
        hits = [e for e in es if e.path.stem == stem] or [e for e in es if stem in e.path.stem]
        if not hits:
            sys.exit(f"No entry or image file matches '{x}'. Entries:\n    " +
                     "\n    ".join(e.path.stem for e in es))
        if len(hits) > 1:
            sys.exit(f"'{x}' matches several entries; be more specific:\n    " +
                     "\n    ".join(e.path.stem for e in hits))
        e = hits[0]
        links = figure_links(e.text)
        print(f"{e.path.stem}: {len(links)} figure(s)")
        files += [(e.path.parent / t).resolve() for t in links]
    for f in files:
        try:
            rel = f.relative_to(ROOT.resolve()).as_posix()
        except ValueError:
            rel = f
        info = png_text(f) if f.exists() and f.suffix.lower() == ".png" else {}
        prov = info.get("Comment") or info.get("Description")
        if not f.exists():
            prov = "(file not found)"
        print(f"{rel}\n    " + (prov.replace("\n", "\n    ") if prov else
                                 "(no provenance recorded: this figure was not saved by the experiment "
                                 "helper's ex.save_figure)"))


