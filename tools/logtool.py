def taken_names():
    """Entry file names already used here or in the group's repository on GitHub."""
    names = {p.name for p in LOG.glob("*.md")}
    if git("remote", check=False):
        try:
            subprocess.run(["git", "fetch", "-q"], cwd=ROOT, capture_output=True, timeout=30)
        except (subprocess.TimeoutExpired, OSError):
            pass
        up = git("rev-parse", "--abbrev-ref", "@{u}", check=False)
        if up:
            names |= {Path(x).name for x in
                      git("ls-tree", "--name-only", up, "log/", check=False).splitlines()}
    return names


