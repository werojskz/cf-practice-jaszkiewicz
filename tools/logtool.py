def remote_url():
    u = git("remote", "get-url", "origin", check=False)
    m = re.match(r"(?:git@github\.com:|https://github\.com/)([^/]+/[^/]+?)(?:\.git)?/?$", u)
    return f"https://github.com/{m.group(1)}" if m else u


def cmd_init(a):
    project = load_project()
    if project.get("initialised") and not a.force:
        sys.exit("This repository is already initialised (project.json).")
    gname = need_git_name()
    print("Initialising the project repository. Press Enter to accept a [default].\n")
    num = a.project if a.project is not None else ask("Project number (see the project list)")
    try:
        num = int(num)
    except (TypeError, ValueError):
        sys.exit("A project number is needed, e.g. 4.")
    title0, ref0 = PROJECTS.get(num, ("", ""))
    title = a.title or ask("Short project title", title0) or "TITLE"
    reference = a.reference or ask("Main reference", ref0) or "REFERENCE"
    group = a.group or ask("Group name, as allocated (e.g. G2)")
    group = re.sub(r"[^A-Za-z0-9_-]", "", group or "")
    if not group:
        sys.exit("A group name is needed.")
    members = []
    if a.member:
        for m in a.member:
            n, _, gh = m.partition(":")
            members.append({"name": n.strip(), "github": gh.strip()})
    else:
        print("\nGroup members: full name exactly as each member set it in "
              "`git config user.name`, and GitHub username. Empty name to finish.")
        while len(members) < 4:
            n = ask(f"  Member {len(members) + 1} full name", gname if not members else "")
            if not n:
                break
            members.append({"name": n, "github": ask(f"  {n}: GitHub username")})
    if not members:
        sys.exit("At least one member is needed.")
    url = remote_url()
    project.update({"initialised": True, "project": num, "title": title, "reference": reference,
                    "group": group, "members": members, "repo_url": url})
    subs = {
        "{{PROJECT}}": str(num), "{{TITLE}}": title, "{{GROUP}}": group,
        "{{REFERENCE}}": reference, "{{REPO_URL}}": url,
        "{{MEMBERS_TABLE}}": "\n".join(
            f"| {m['name']} | " + (f"[@{m['github']}](https://github.com/{m['github']})"
                                   if m["github"] else "") + " |" for m in members),
        "{{MEMBERS_TEX}}": ", ".join(tex_escape(m["name"]) for m in members),
        "{{MEMBERS_CONTRIB}}": "".join(f"{tex_escape(m['name'])} & \\dots \\\\\n" for m in members),
        "{{REFERENCE_TEX}}": tex_escape(reference),
    }
    for rel in ("README.md", "report/report.tex"):
        f = ROOT / rel
        if f.exists():
            t = f.read_text(encoding="utf-8")
            for k, v in subs.items():
                t = t.replace(k, v)
            f.write_text(t, encoding="utf-8")
    (ROOT / "project.json").write_text(json.dumps(project, indent=2, ensure_ascii=False) + "\n",
                                       encoding="utf-8")
    cmd_index(a, quiet=True)
    if gname not in member_names(project):
        print(f"\nwarning: your Git name '{gname}' is not one of the member names.")
    git("add", "-A")
    git("commit", "-q", "-m", f"Initialise project {num}, group {group}")
    print(f"\nInitialised project {num} ({title}), group {group}: "
          + ", ".join(member_names(project)))
    push()
